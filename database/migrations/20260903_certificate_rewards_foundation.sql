-- Fail closed before changing attendance uniqueness. Existing duplicate data
-- must be resolved explicitly rather than being deleted by this migration.
DO $$
DECLARE
  duplicate_report TEXT;
BEGIN
  SELECT string_agg(
    format('(event_id=%L, registration_id=%L, count=%s)', event_id, registration_id, duplicate_count),
    '; '
    ORDER BY event_id, registration_id
  )
  INTO duplicate_report
  FROM (
    SELECT event_id, registration_id, COUNT(*) AS duplicate_count
    FROM attendance
    GROUP BY event_id, registration_id
    HAVING COUNT(*) > 1
  ) duplicates;

  IF duplicate_report IS NOT NULL THEN
    RAISE EXCEPTION
      'Cannot apply attendance uniqueness migration: duplicate (event_id, registration_id) rows exist: %',
      duplicate_report;
  END IF;
END
$$;

DO $$
DECLARE
  null_event_count BIGINT;
BEGIN
  SELECT COUNT(*)
  INTO null_event_count
  FROM attendance
  WHERE event_id IS NULL;

  IF null_event_count > 0 THEN
    RAISE EXCEPTION
      'Cannot apply attendance migration: % attendance row(s) have NULL event_id',
      null_event_count;
  END IF;
END
$$;

