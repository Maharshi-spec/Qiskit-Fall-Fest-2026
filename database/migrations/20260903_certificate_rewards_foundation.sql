-- Remove only single-column UNIQUE constraints on registration_id. Primary keys,
-- foreign keys, and NOT NULL constraints are intentionally untouched.
DO $$
DECLARE
  constraint_record RECORD;
BEGIN
  FOR constraint_record IN
    SELECT con.conname
    FROM pg_constraint con
    JOIN pg_attribute att
      ON att.attrelid = con.conrelid
     AND att.attnum = con.conkey[1]
    WHERE con.conrelid = 'attendance'::regclass
      AND con.contype = 'u'
      AND array_length(con.conkey, 1) = 1
      AND att.attname = 'registration_id'
  LOOP
    EXECUTE format('ALTER TABLE attendance DROP CONSTRAINT %I', constraint_record.conname);
  END LOOP;
END
$$;

-- Remove an equivalent standalone unique index only if it is not backing a
-- remaining constraint. This handles databases where the legacy uniqueness
-- was created as an index rather than a table constraint.
DO $$
DECLARE
  index_record RECORD;
BEGIN
  FOR index_record IN
    SELECT index_name
    FROM (
      SELECT idx.relname AS index_name,
             indexrel.indkey,
             indexrel.indisunique,
             indexrel.indisprimary,
             EXISTS (
               SELECT 1
               FROM pg_constraint con
               WHERE con.conindid = indexrel.indexrelid
             ) AS backs_constraint
      FROM pg_class table_rel
      JOIN pg_index indexrel ON indexrel.indrelid = table_rel.oid
      JOIN pg_class idx ON idx.oid = indexrel.indexrelid
      WHERE table_rel.oid = 'attendance'::regclass
    ) attendance_indexes
    WHERE indisunique
      AND NOT indisprimary
      AND NOT backs_constraint
      AND indkey = ARRAY[
        (SELECT attnum FROM pg_attribute WHERE attrelid = 'attendance'::regclass AND attname = 'registration_id')::int2
      ]::int2vector
  LOOP
    EXECUTE format('DROP INDEX %I', index_record.index_name);
  END LOOP;
END
$$;

