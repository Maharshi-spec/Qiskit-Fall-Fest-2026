-- A unique index cannot span hackathon_results and teams. This trigger enforces
-- one occurrence of each placement within a HACKATHON event without adding a
-- redundant event_id column to hackathon_results.
CREATE OR REPLACE FUNCTION enforce_hackathon_result_rules()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  result_event_id VARCHAR(64);
  result_event_type VARCHAR(32);
BEGIN
  SELECT team.event_id, event.event_type
  INTO result_event_id, result_event_type
  FROM teams team
  JOIN events event ON event.event_id = team.event_id
  WHERE team.id = NEW.team_id;

  IF result_event_id IS NULL THEN
    RAISE EXCEPTION 'Hackathon result team % does not exist or has no event', NEW.team_id;
  END IF;

  IF result_event_type <> 'HACKATHON' THEN
    RAISE EXCEPTION 'Hackathon result team % belongs to non-hackathon event %', NEW.team_id, result_event_id;
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended(result_event_id || ':' || NEW.placement, 0)
  );

  IF EXISTS (
    SELECT 1
    FROM hackathon_results existing_result
    JOIN teams existing_team ON existing_team.id = existing_result.team_id
    WHERE existing_team.event_id = result_event_id
      AND existing_result.placement = NEW.placement
      AND existing_result.id <> COALESCE(NEW.id, 0)
  ) THEN
    RAISE EXCEPTION 'Placement % is already assigned within hackathon event %', NEW.placement, result_event_id;
  END IF;

  RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS hackathon_result_rules_trigger ON hackathon_results;

CREATE TRIGGER hackathon_result_rules_trigger
  BEFORE INSERT OR UPDATE OF team_id, placement ON hackathon_results
  FOR EACH ROW
  EXECUTE FUNCTION enforce_hackathon_result_rules();

COMMIT;